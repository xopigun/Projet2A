static void bench_fill_bench_cfg(bench_bench_cfg_t *frame,
                                        const double *values) {
    frame->target_node = (uint8_t)values[0];
    frame->mode = (uint8_t)values[1];
    frame->param_u16 = (uint16_t)values[2];
    frame->duration_ms = (uint16_t)values[3];
    frame->heartbeat_period_ms = (uint16_t)values[4];
}

static void bench_fill_bench_result(bench_bench_result_t *frame,
                                        const double *values) {
    frame->node_id = (uint8_t)values[0];
    frame->mode = (uint8_t)values[1];
    frame->status = (uint8_t)values[2];
    frame->arm_rx = (uint8_t)values[3];
    frame->frames_sent = (uint16_t)values[4];
    frame->frames_lost = (uint16_t)values[5];
}

static void bench_fill_heartbeat(bench_heartbeat_t *frame,
                                        const double *values) {
    frame->ctrl_state = (uint8_t)values[0];
    frame->last_error_code = (uint8_t)values[1];
    frame->clock_not_qualified = (uint8_t)values[2];
    frame->fault_mode_active = (uint8_t)values[3];
    frame->silent_mode = (uint8_t)values[4];
    frame->tec = (uint8_t)values[5];
    frame->rec = (uint8_t)values[6];
    frame->current_mode = (uint8_t)values[7];
    frame->reserved = (uint8_t)values[8];
    frame->rx_fifo_lost = (uint8_t)values[9];
    frame->ring_overflow = (uint8_t)values[10];
    frame->non_classic_rx = (uint8_t)values[11];
    frame->ext_id_rx = (uint8_t)values[12];
}

static void bench_fill_energy_command(bench_energy_command_t *frame,
                                        const double *values) {
    frame->torque_setpoint = (float)values[0];
    frame->speed_setpoint = (float)values[1];
    frame->current_limit = (float)values[2];
    frame->enable = (uint8_t)values[3];
    frame->direction = (uint8_t)values[4];
    frame->command_counter = (uint8_t)values[5];
    frame->checksum = (uint8_t)values[6];
}

static void bench_fill_imu_speed(bench_imu_speed_t *frame,
                                        const double *values) {
    frame->accel_x = (float)values[0];
    frame->accel_y = (float)values[1];
    frame->gyro_z = (float)values[2];
    frame->wheel_speed = (float)values[3];
    frame->sensor_present = (uint8_t)values[4];
    frame->frame_counter = (uint8_t)values[5];
}

static void bench_fill_temp_battery(bench_temp_battery_t *frame,
                                        const double *values) {
    frame->temperature = (float)values[0];
    frame->pack_voltage = (float)values[1];
    frame->pack_current = (float)values[2];
    frame->state_of_charge = (uint8_t)values[3];
    frame->sensor_present = (uint8_t)values[4];
    frame->frame_counter = (uint8_t)values[5];
}

int bench_vector_pack(const bench_vector_t *vector, uint8_t *out) {
    memset(out, 0, 8);

    if (strcmp(vector->frame, "BENCH_CFG") == 0) {
        bench_bench_cfg_t frame;
        memset(&frame, 0, sizeof(frame));
        bench_fill_bench_cfg(&frame, vector->values);
        bench_bench_cfg_pack(out, &frame);
        return 1;
    } else if (strcmp(vector->frame, "BENCH_RESULT") == 0) {
        bench_bench_result_t frame;
        memset(&frame, 0, sizeof(frame));
        bench_fill_bench_result(&frame, vector->values);
        bench_bench_result_pack(out, &frame);
        return 1;
    } else if (strcmp(vector->frame, "HEARTBEAT") == 0) {
        bench_heartbeat_t frame;
        memset(&frame, 0, sizeof(frame));
        bench_fill_heartbeat(&frame, vector->values);
        bench_heartbeat_pack(out, &frame);
        return 1;
    } else if (strcmp(vector->frame, "ENERGY_COMMAND") == 0) {
        bench_energy_command_t frame;
        memset(&frame, 0, sizeof(frame));
        bench_fill_energy_command(&frame, vector->values);
        bench_energy_command_pack(out, &frame);
        return 1;
    } else if (strcmp(vector->frame, "IMU_SPEED") == 0) {
        bench_imu_speed_t frame;
        memset(&frame, 0, sizeof(frame));
        bench_fill_imu_speed(&frame, vector->values);
        bench_imu_speed_pack(out, &frame);
        return 1;
    } else if (strcmp(vector->frame, "TEMP_BATTERY") == 0) {
        bench_temp_battery_t frame;
        memset(&frame, 0, sizeof(frame));
        bench_fill_temp_battery(&frame, vector->values);
        bench_temp_battery_pack(out, &frame);
        return 1;
    }

    return 0;  /* trame sans signal : ARM et GO */
}
